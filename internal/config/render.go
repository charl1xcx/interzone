// HostName is the inventory name MDAD uses for the server.
func (c *Config) HostName() string { return "matrix." + c.Domain }

type yamlWriter struct {
	b    strings.Builder
	seen map[string]bool
}

func (w *yamlWriter) section(title string) {
	fmt.Fprintf(&w.b, "\n# ── %s %s\n", title, strings.Repeat("─", max(3, 60-len(title))))
}

func (w *yamlWriter) comment(s string) { fmt.Fprintf(&w.b, "# %s\n", s) }

// raw writes an already-formatted scalar. Later writes of the same key are
// dropped so components that share a variable never produce duplicates.
func (w *yamlWriter) raw(key, value string) {
	if w.seen[key] {
		return
	}
	w.seen[key] = true
	fmt.Fprintf(&w.b, "%s: %s\n", key, value)
}

func (w *yamlWriter) str(key, value string) { w.raw(key, Quote(value)) }

func (w *yamlWriter) block(key, body string) {
	if w.seen[key] {
		return
	}
	w.seen[key] = true
	body = strings.TrimRight(body, "\n ")
	if strings.HasPrefix(body, "|") || strings.HasPrefix(body, ">") {
		head, rest, _ := strings.Cut(body, "\n")
		fmt.Fprintf(&w.b, "%s: %s\n%s\n", key, head, rest)
		return
	}
	fmt.Fprintf(&w.b, "%s:\n%s\n", key, indent(body, "  "))
}

func indent(s, pad string) string {
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		if l != "" {
			lines[i] = pad + l
		}
	}
	return strings.Join(lines, "\n")
}

// Quote renders s as a single-quoted YAML scalar.
func Quote(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

var numeric = regexp.MustCompile(`^-?[0-9]+(\.[0-9]+)?$`)

func (w *yamlWriter) field(f catalog.Field, v string) {
	if v == "" && !f.Required {
		return
	}
	switch f.Kind {
	case catalog.Bool:
		if v != "true" {
			v = "false"
		}
		w.raw(f.Var, v)
	case catalog.Number:
		if numeric.MatchString(v) {
			w.raw(f.Var, v)
		} else {
			w.str(f.Var, v)
		}
	case catalog.List:
		var items []string
		for _, it := range strings.Split(v, ",") {
			if it = strings.TrimSpace(it); it != "" {
				items = append(items, "- "+Quote(it))
			}
		}
		if len(items) == 0 {
			w.raw(f.Var, "[]")
		} else {
			w.block(f.Var, strings.Join(items, "\n"))
		}
	case catalog.YAML:
		w.block(f.Var, v)
	default:
		w.str(f.Var, v)
	}
}

// MigrationVersion reads the value MDAD expects from the playbook's own example config.
func MigrationVersion(playbookDir string) string {
	b, err := os.ReadFile(playbookDir + "/examples/vars.yml")
	if err != nil {
		return ""
	}
	m := regexp.MustCompile(`(?m)^matrix_playbook_migration_validated_version:\s*(\S+)`).FindSubmatch(b)
	if m == nil {
		return ""
	}
	return string(m[1])
}

// VarsYAML renders inventory/host_vars/matrix.<domain>/vars.yml.
// certPath/keyPath are only used for the self-signed and custom SSL modes.
func (c *Config) VarsYAML(migrationVersion, certPath, keyPath string) string {
	w := &yamlWriter{seen: map[string]bool{}}
	fmt.Fprintf(&w.b, "# Generated by interzone on %s.\n", time.Now().Format("2006-01-02 15:04"))
	w.comment("Re-running interzone rewrites this file. Put hand-written settings in the")
	w.comment("\"Extra vars\" box inside interzone so they survive.")
	w.b.WriteString("---\n")

	w.section("Basics")
	if migrationVersion == "" {
		migrationVersion = "''  # filled in from the playbook during deploy"
	}
	w.raw("matrix_playbook_migration_validated_version", migrationVersion)
	w.str("matrix_domain", c.Domain)
	w.raw("matrix_homeserver_implementation", c.Homeserver)
	w.str("matrix_homeserver_generic_secret_key", c.GenericSecret)
	w.raw("matrix_playbook_reverse_proxy_type", "playbook-managed-traefik")
	w.raw("devture_systemd_docker_base_ipv6_enabled", fmt.Sprint(c.IPv6))
	w.str("postgres_connection_password", c.PostgresPassword)
	w.raw("matrix_homeserver_federation_enabled", fmt.Sprint(c.Federation))

	w.section("Mirrors")
	if c.Sources.UseRegistry && c.Sources.RegistryPrefix != "" {
		w.comment("Every container image is pulled from this registry instead of docker.io, ghcr.io, etc.")
		w.str("matrix_container_global_registry_prefix_override", normalizePrefix(c.Sources.RegistryPrefix))
		// The RustPush role is not wired to the global override upstream.
		w.raw("matrix_bridge_rustpush_container_image_registry_prefix_upstream", `"{{ matrix_container_global_registry_prefix_override }}"`)
	} else {
		w.comment("Images are pulled from their upstream registries.")
	}
	if c.Sources.DockerPackageURL != "" {
		w.comment("Docker Engine packages come from this mirror of download.docker.com/linux.")
		w.str("docker_repo_url", strings.TrimRight(c.Sources.DockerPackageURL, "/"))
	}

	w.section("SSL certificates")
	switch c.SSL.Mode {
	case "letsencrypt":
		if c.SSL.ACMEEmail != "" {
			w.str("traefik_config_certificatesResolvers_acme_email", c.SSL.ACMEEmail)
		} else {
			w.comment("Let's Encrypt without a contact email.")
		}
	case "none":
		w.comment("No HTTPS: put your own TLS-terminating proxy in front of this server.")
		w.raw("traefik_config_entrypoint_web_secure_enabled", "false")
	case "selfsigned", "custom":
		w.raw("traefik_config_certificatesResolvers_acme_enabled", "false")
		w.raw("traefik_ssl_dir_enabled", "true")
		w.block("traefik_provider_configuration_extension_yaml", strings.TrimSpace(`
tls:
  certificates:
    - certFile: /ssl/cert.pem
      keyFile: /ssl/privkey.pem
  stores:
    default:
      defaultCertificate:
        certFile: /ssl/cert.pem
        keyFile: /ssl/privkey.pem`))
		w.block("aux_file_definitions", fmt.Sprintf(`- dest: "{{ traefik_ssl_dir_path }}/privkey.pem"
  src: %s
  mode: '0600'
- dest: "{{ traefik_ssl_dir_path }}/cert.pem"
  src: %s`, Quote(keyPath), Quote(certPath)))
	}

	w.section("First admin user")
	switch c.Homeserver {
	case "synapse", "dendrite":
		w.block("matrix_user_creator_users_additional", fmt.Sprintf("- username: %s\n  initial_password: %s\n  initial_type: admin",
			Quote(c.AdminUser), Quote(c.AdminPassword)))
	case "continuwuity", "tuwunel":
		if c.CloseRegistration {
			w.comment("Registration was closed from interzone's Manage menu.")
			w.raw("matrix_"+c.Homeserver+"_config_allow_registration", "false")
			break
		}
		w.comment("These servers can't create users from Ansible. Register the first account")
		w.comment("from any client using this token, then close registration from interzone.")
		w.raw("matrix_"+c.Homeserver+"_config_allow_registration", "true")
		w.str("matrix_"+c.Homeserver+"_config_registration_token", c.AdminPassword)
	case "conduit":
		if c.CloseRegistration {
			w.comment("Registration was closed from interzone's Manage menu.")
			w.raw("matrix_conduit_allow_registration", "false")
			break
		}
		w.comment("Conduit can't create users from Ansible. Registration is open until you")
		w.comment("create your account; close it afterwards from interzone's Manage menu.")
		w.raw("matrix_conduit_allow_registration", "true")
	}

	w.section("Components")
	for _, cat := range catalog.Categories {
		var comps []catalog.Component
		for _, comp := range catalog.Components {
			if comp.Category != cat {
				continue
			}
			if c.Enabled(comp) || (comp.DefaultOn && comp.EnableVar != "") {
				comps = append(comps, comp)
			}
		}
		if len(comps) == 0 {
			continue
		}
		fmt.Fprintf(&w.b, "\n# %s\n", cat)
		for _, comp := range comps {
			on := c.Enabled(comp)
			if comp.EnableVar != "" {
				w.raw(comp.EnableVar, fmt.Sprint(on))
			}
			if !on {
				continue
			}
			keys := make([]string, 0, len(comp.Extra))
			for k := range comp.Extra {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for _, k := range keys {
				w.raw(k, comp.Extra[k])
			}
			for _, f := range comp.Fields {
				if f.ShowIf != "" && c.Values[f.ShowIf] != "true" {
					continue
				}
				w.field(f, c.Values[f.Var])
			}
		}
	}

	if extra := strings.TrimSpace(c.ExtraYAML); extra != "" {
		w.section("Extra vars (hand-written)")
		w.b.WriteString(extra + "\n")
	}
	return w.b.String()
}

func normalizePrefix(p string) string {
	p = strings.TrimPrefix(strings.TrimPrefix(strings.TrimSpace(p), "https://"), "http://")
	return strings.TrimRight(p, "/") + "/"
}

// HostsINI renders inventory/hosts.
func (c *Config) HostsINI() string {
	var b strings.Builder
	b.WriteString("# Generated by interzone.\n[matrix_servers]\n")
	parts := []string{c.HostName()}
	t := c.Target
	if t.Mode == "local" {
		parts = append(parts, "ansible_connection=local")
		if os.Geteuid() != 0 {
			parts = append(parts, "ansible_become=true", "ansible_become_user=root")
		}
	} else {
		parts = append(parts, "ansible_host="+t.Host, "ansible_ssh_user="+t.User)
		if t.Port != "" && t.Port != "22" {
			parts = append(parts, "ansible_port="+t.Port)
		}
		if t.SSHKey != "" {
			parts = append(parts, "ansible_ssh_private_key_file="+t.SSHKey)
		}
		if t.User != "root" {
			parts = append(parts, "ansible_become=true", "ansible_become_user=root")
		}
	}
	if t.BecomePass != "" {
		parts = append(parts, "ansible_become_password="+Quote(t.BecomePass))
	}
	b.WriteString(strings.Join(parts, " ") + "\n")
	return b.String()
}

// DNSRecords lists the hostnames that must point at the server.
func (c *Config) DNSRecords() []string {
	recs := []string{"matrix." + c.Domain}
	for _, comp := range catalog.Components {
		if comp.Subdomain != "" && c.Enabled(comp) {
			recs = append(recs, comp.Subdomain+"."+c.Domain)
		}
	}
	if c.Components["base-domain"] {
		recs = append(recs, c.Domain)
	}
	return recs
}
