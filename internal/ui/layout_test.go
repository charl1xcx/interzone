// The layout tests draw the main screens at a phone's size and a desktop
// terminal's and compare them with testdata/layout. After a deliberate
// change, look at the diff and accept it with
//
//	go test ./internal/ui -run Layout -update

var update = flag.Bool("update", false, "rewrite the layout golden files")

// stamp is vars.yml's generation time, zeroed before comparing.
var stamp = regexp.MustCompile(`Generated by interzone on [0-9: -]*|\b[0-9]{4}-[0-9]{2}-[0-9]{2}( [0-9]{2}:[0-9]{2})?`)

var sizes = []struct{ w, h int }{{46, 40}, {120, 36}}

// demoApp is a fresh app on a fixed demo config, with the config and data
// directories somewhere harmless.
func demoApp(t *testing.T, w, h int) *App {
	t.Helper()
	t.Setenv("HOME", "/home/demo")
	t.Setenv("XDG_CONFIG_HOME", t.TempDir())
	t.Setenv("XDG_DATA_HOME", "/home/demo/.local/share")
	t.Setenv("INTERZONE_SERVER", "")
	lipgloss.SetColorProfile(termenv.Ascii)

	cfg := config.Default()
	cfg.Domain = "example.org"
	cfg.PlaybookDir = "/home/demo/.local/share/interzone/matrix-docker-ansible-deploy"
	for _, id := range []string{"element", "cinny", "coturn", "double-puppet"} {
		cfg.Components[id] = true
	}
	a := New(cfg, true)
	a.step = 0
	a.Update(tea.WindowSizeMsg{Width: w, Height: h})
	return a
}

