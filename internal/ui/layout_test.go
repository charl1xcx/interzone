// The layout tests draw the main screens at a phone's size and a desktop
// terminal's and compare them with testdata/layout. After a deliberate
// change, look at the diff and accept it with
//
//	go test ./internal/ui -run Layout -update

var update = flag.Bool("update", false, "rewrite the layout golden files")

// stamp is vars.yml's generation time, zeroed before comparing.
var stamp = regexp.MustCompile(`Generated by interzone on [0-9: -]*`)

var sizes = []struct{ w, h int }{{46, 40}, {120, 36}}

// demoApp is a fresh app on a fixed demo config, with the config and data
// directories somewhere harmless.
func demoApp(t *testing.T, w, h int) *App {
	t.Helper()
	t.Setenv("HOME", "/home/demo")
	t.Setenv("XDG_CONFIG_HOME", t.TempDir())
	t.Setenv("XDG_DATA_HOME", "/home/demo/.local/share")
	t.Setenv("INTERZONE_SERVER", "")
	lipgloss.SetColorProfile(termenv.Ascii)

	cfg := config.Default()
	cfg.Domain = "example.org"
	cfg.PlaybookDir = "/home/demo/.local/share/interzone/matrix-docker-ansible-deploy"
	for _, id := range []string{"element", "cinny", "coturn", "double-puppet"} {
		cfg.Components[id] = true
	}
	a := New(cfg, true)
	a.step = 0
	a.Update(tea.WindowSizeMsg{Width: w, Height: h})
	return a
}

func TestLayout(t *testing.T) {
	shots := []struct {
		name string
		open func(a *App)
	}{
		{"welcome", func(a *App) {}},
		{"server", func(a *App) { a.jump(a.index("Server")) }},
		{"homeserver", func(a *App) { a.jump(a.index("Homeserver")) }},
		{"components", func(a *App) { a.jump(a.index("Components")) }},
		{"settings", func(a *App) {
			a.jump(a.index("Components"))
			a.cur().(*componentsScreen).openDetails()
		}},
		{"review", func(a *App) { a.jump(a.index("Review")) }},
		{"manage", func(a *App) {
			a.jump(a.index("Manage"))
			a.health = &deploy.Health{Up: true, Trusted: true, CertLeft: 63*24*time.Hour + time.Hour}
		}},
		{"manage-armed", func(a *App) {
			a.jump(a.index("Manage"))
			a.Update(tea.KeyMsg{Type: tea.KeyRunes, Runes: []rune("r")})
		}},
		{"menu", func(a *App) {
			a.jump(a.index("Manage"))
			if a.compact() {
				a.menuOpen = true
			}
		}},
	}
	for _, sz := range sizes {
		for _, sh := range shots {
			name := fmt.Sprintf("%s-%dx%d", sh.name, sz.w, sz.h)
			t.Run(name, func(t *testing.T) {
				a := demoApp(t, sz.w, sz.h)
				sh.open(a)
				got := stamp.ReplaceAllStringFunc(ansi.Strip(a.View()), func(m string) string {
					return strings.Map(func(r rune) rune {
						if r >= '0' && r <= '9' {
							return '0'
						}
						return r
					}, m)
				})
				lines := strings.Split(got, "\n")
				if len(lines) > sz.h {
					t.Errorf("%d lines, taller than the %d-line terminal", len(lines), sz.h)
				}
				for i, l := range lines {
					if lw := ansi.StringWidth(l); lw > sz.w {
						t.Errorf("line %d is %d wide, more than %d: %q", i+1, lw, sz.w, l)
					}
				}
				golden(t, name, got)
			})
		}
	}
}

func golden(t *testing.T, name, got string) {
	t.Helper()
	path := filepath.Join("testdata", "layout", name+".txt")
	if *update {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run with -update to create it)", err)
	}
	if string(want) != got {
		t.Errorf("%s changed; if that's intended, rerun with -update.\n--- want\n%s\n--- got\n%s", path, want, got)
	}
}
