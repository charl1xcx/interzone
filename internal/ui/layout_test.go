func shootAll(t *testing.T, sizes []struct{ w, h int }, shots []struct {
	name string
	open func(a *App)
}) {
	for _, sz := range sizes {
		for _, sh := range shots {
			name := fmt.Sprintf("%s-%dx%d", sh.name, sz.w, sz.h)
			t.Run(name, func(t *testing.T) {
				a := demoApp(t, sz.w, sz.h)
				sh.open(a)
				got := stamp.ReplaceAllStringFunc(ansi.Strip(a.View()), func(m string) string {
					return strings.Map(func(r rune) rune {
						if r >= '0' && r <= '9' {
							return '0'
						}
						return r
					}, m)
				})
				lines := strings.Split(got, "\n")
				if len(lines) > sz.h {
					t.Errorf("%d lines, taller than the %d-line terminal", len(lines), sz.h)
				}
				for i, l := range lines {
					if lw := ansi.StringWidth(l); lw > sz.w {
						t.Errorf("line %d is %d wide, more than %d: %q", i+1, lw, sz.w, l)
					}
				}
				golden(t, name, got)
			})
		}
	}
}

func golden(t *testing.T, name, got string) {
	t.Helper()
	path := filepath.Join("testdata", "layout", name+".txt")
	if *update {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run with -update to create it)", err)
	}
	if string(want) != got {
		t.Errorf("%s changed; if that's intended, rerun with -update.\n--- want\n%s\n--- got\n%s", path, want, got)
	}
}

// With every menu section open in a short window, the sidebar scrolls to
// where you are instead of pushing the header off the screen.
func TestSidebarFits(t *testing.T) {
	a := demoApp(t, 120, 24)
	a.jump(a.index("Manage"))
	for sec := range sectionNames {
		a.sideOpen[sec] = true
	}
	lines := strings.Split(ansi.Strip(a.View()), "\n")
	if len(lines) != 24 || !strings.Contains(lines[0], "interzone") || !strings.Contains(a.View(), "Overview") {
		t.Errorf("%d lines, the first %q:\n%s", len(lines), lines[0], strings.Join(lines, "\n"))
	}
}
